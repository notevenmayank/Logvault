"""
Sentinel Vault — MCP Server (Pillar 1)

Exposes the vault's verification logic as discoverable MCP tools, so any
MCP-aware AI agent (here, soc_agent.py running Qwen 2.5) can investigate
the system the way a SOC analyst would: ask a question, call the right
tool, read the result, answer in plain English.

This server does NOT decide anything itself — every tool here is a thin
wrapper around the same deterministic verification_core.py logic the
dashboard already uses. The AI agent that calls these tools only
explains and summarizes what the tools return; it never overrides a
status.

Run standalone to sanity-check it (prints nothing, waits for an MCP
client over stdio):
    python mcp_server.py

Normally you don't run this directly — soc_agent.py launches it as a
subprocess automatically.
"""
from mcp.server.mcpserver import MCPServer
import verification_core
import ollama_explainer

server = MCPServer(
    "SentinelVault",
    instructions=(
        "Tools for investigating the Sentinel Vault tamper-proof security log system. "
        "Use verify_integrity for an overall status check, get_alerts to see only the "
        "problems, inspect_ledger to look at one specific window in detail, and "
        "analyze_incident to get a plain-English explanation of why a window is flagged."
    ),
)


@server.tool()
def verify_integrity() -> dict:
    """
    Runs a full integrity check across every window in the vault and
    returns a summary: how many windows are Intact, Tampered, Missing,
    or Not Yet On-Chain, plus the total count. Use this first for a
    quick overall health check of the log vault.
    """
    results, error = verification_core.get_all_window_statuses()
    summary = {
        "total": len(results),
        "intact": sum(1 for r in results if r["status"] == "INTACT"),
        "tampered": sum(1 for r in results if r["status"] == "TAMPERED"),
        "missing": sum(1 for r in results if r["status"] == "MISSING"),
        "not_on_chain": sum(1 for r in results if r["status"] == "NOT_ON_CHAIN"),
    }
    if error:
        summary["warning"] = error
    return summary


@server.tool()
def get_alerts() -> list:
    """
    Returns only the windows that are currently flagged as a problem
    (TAMPERED or MISSING) — the ones a security analyst actually needs
    to look at. Each alert includes the window ID, status, line count,
    and the exact tampered line number(s) if known.
    """
    results, _ = verification_core.get_all_window_statuses()
    alerts = []
    for r in results:
        if r["status"] in ("TAMPERED", "MISSING"):
            alerts.append({
                "window_id": r["window_id"],
                "status": r["status"],
                "num_lines": r.get("num_lines"),
                "tampered_lines": r.get("tampered_lines"),
            })
    return alerts


@server.tool()
def inspect_ledger(window_id: int) -> dict:
    """
    Returns the full detail recorded for one specific window ID,
    including its on-chain hash, recomputed hash, line count, and
    status. Use this when you need to look closely at one window
    rather than the whole vault.
    """
    results, _ = verification_core.get_all_window_statuses()
    for r in results:
        if r["window_id"] == window_id:
            return r
    return {"error": f"No window with ID {window_id} found."}


@server.tool()
def analyze_incident(window_id: int) -> str:
    """
    Returns a plain-English explanation of why a specific window is
    flagged as TAMPERED or MISSING, generated by the local AI model.
    This only explains an already-confirmed, deterministic result from
    inspect_ledger — it never decides tamper status itself.
    """
    results, _ = verification_core.get_all_window_statuses()
    for r in results:
        if r["window_id"] == window_id:
            if r["status"] not in ("TAMPERED", "MISSING"):
                return f"Window {window_id} is {r['status']} — nothing to analyze, it's fine."
            return ollama_explainer.explain_window(r) or "No explanation available."
    return f"No window with ID {window_id} found."


if __name__ == "__main__":
    server.run()
